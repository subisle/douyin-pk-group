#!/usr/bin/env bash
# 一键铺 3328 开发环境（3328 恢复后跑一次）
# 用法：bash scripts/dev/setup-rk3328.sh
# 前置：Mac 上已跑过 ship-rk3328.sh 产出二进制；本地 rust/.env 有现成配置
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
# 内网地址不进公开仓库：两个地址都由环境变量提供
RK3328_HOST="${RK3328_HOST:?请设置 RK3328_HOST（rk3328 局域网地址）}"
PK_HOST="${PK_HOST:?请设置 PK_HOST（3318 生产内网地址）}"
DEST="root@$RK3328_HOST"
SSH="ssh -o ConnectTimeout=15 $DEST"
D=/opt/pk-dev

echo "==> 1/5 上传二进制 + 前端 + 脚本 + 单元文件"
$SSH "mkdir -p $D/data"
rsync -z --chmod=F755 "$ROOT/rust/target/aarch64-unknown-linux-gnu/release/pk-server" "$DEST:$D/pk-server"
rsync -a --delete "$ROOT/apps/douyin-web/dist/" "$DEST:$D/web/"
rsync "$ROOT/scripts/dev/rk3328-guard.sh" "$DEST:$D/guard.sh"
rsync "$ROOT/scripts/dev/pk-dev.service" "$DEST:/etc/systemd/system/pk-dev.service"
rsync "$ROOT/scripts/dev/pk-dev-guard.service" "$DEST:/etc/systemd/system/pk-dev-guard.service"
rsync "$ROOT/scripts/dev/pk-dev-guard.timer" "$DEST:/etc/systemd/system/pk-dev-guard.timer"
$SSH "chmod +x $D/guard.sh"

echo "==> 2/5 生成 .env（数据库指向 3318 的 pk-postgres，dev 独立端口 8790）"
# 密码直接从 3318 的现网 .env 取，避免手抄
PGPASS=$(ssh -o ConnectTimeout=10 "root@$PK_HOST" "grep -m1 '^DB_LOCAL_PASSWORD=' /opt/pk-server/.env | cut -d= -f2-")
[[ -n "$PGPASS" ]] || { echo "取不到 3318 的 DB 密码"; exit 1; }
$SSH "grep -q PK_DEV_MARKER $D/.env 2>/dev/null || cat > $D/.env <<ENVEOF
# PK_DEV_MARKER: generated by setup-rk3328.sh
PORT=8790
HOST=0.0.0.0
WEB_DIST=$D/web
SQLITE_PATH=$D/data/app.db
ADMIN_PASSWORD=${RK3328_ADMIN_PASSWORD:?请设置 RK3328_ADMIN_PASSWORD（dev 管理员口令，勿用弱口令）}
# 业务库 = 3318 上的 pk-postgres（生产同一个库，dev 实例以读为主，写小心）
DB_LOCAL_HOST=$PK_HOST
DB_LOCAL_PORT=5432
DB_LOCAL_NAME=douyin
DB_LOCAL_USER=douyin_admin
DB_LOCAL_PASSWORD=$PGPASS
DB_LOCAL_POOL_LIMIT=4
DB_WRITER_HOST=$PK_HOST
DB_WRITER_PORT=5432
DB_WRITER_NAME=douyin
DB_WRITER_USER=douyin_admin
DB_WRITER_PASSWORD=$PGPASS
DB_MIGRATOR_HOST=$PK_HOST
DB_MIGRATOR_PORT=5432
DB_MIGRATOR_NAME=douyin
DB_MIGRATOR_USER=douyin_admin
DB_MIGRATOR_PASSWORD=$PGPASS
ENVEOF
chmod 600 $D/.env"

echo "==> 3/5 systemd 启用 pk-dev + 守卫 timer"
$SSH "systemctl daemon-reload && systemctl enable --now pk-dev-guard.timer && systemctl restart pk-dev"

echo "==> 4/5 健康检查"
sleep 4
$SSH "systemctl is-active pk-dev && curl -m 5 -s http://127.0.0.1:8790/api/health | head -c 200 || journalctl -u pk-dev -n 20 --no-pager"

echo "==> 5/5 守卫首跑"
$SSH "/opt/pk-dev/guard.sh; cat /run/pk-dev-guard.status"
echo "==> 完成。局域网入口：http://$RK3328_HOST:8790/"

/** 改名前的老赛事名 → 新赛事名（2026-10-09 改版）。
 *  库里由 Rust 启动迁移统一改名，这里再兜一层：万一前端拿到没迁过的老方案也能对上赛制。 */
const LEGACY_EVENT_NAMES: Record<string, EventType> = {
  初级: '初级争霸赛小组赛',
  中级争霸赛: '中级争霸赛小组赛',
  月底争霸赛: '月终争霸赛',
  初级晋级赛: '初级争霸赛晋级赛',
  中级晋级赛: '中级争霸赛晋级赛',
  // 2026-10-09 拆分前最早的「晋级赛」没有级别，按初级归档
  晋级赛: '初级争霸赛晋级赛',
};

export function rulesOf(eventType: string): EventRule | undefined {
  const key = LEGACY_EVENT_NAMES[eventType] ?? (eventType as EventType);
  return EVENT_RULES[key];
}
